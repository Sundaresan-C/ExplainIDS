"""PDF incident report for one analysis run (reportlab)."""
from __future__ import annotations

import io
import time

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from config import MITIGATION, SEVERITY

_SEV_ORDER = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3, "None": 4}


def build_report(result: pd.DataFrame, source_name: str, analyst: str = "", notes: str = "",
                 model_info: dict | None = None) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=1.8 * cm, rightMargin=1.8 * cm,
                            topMargin=1.6 * cm, bottomMargin=1.6 * cm, title="ExplainIDS Incident Report")
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], textColor=colors.HexColor("#0f172a"))
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=colors.HexColor("#1d4ed8"))
    body = ss["BodyText"]
    small = ParagraphStyle("small", parent=body, fontSize=8, leading=10)

    n = len(result)
    att = result[result["Verdict"] != "Benign"]
    worst = min((_SEV_ORDER[s] for s in att["Severity"]), default=4)
    worst_name = [k for k, v in _SEV_ORDER.items() if v == worst][0]
    grid = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cbd5e1")),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e293b")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")])]

    el = [Paragraph("ExplainIDS: Network Incident Report", h1),
          Paragraph(f"Generated {time.strftime('%Y-%m-%d %H:%M')} · Source: <b>{source_name}</b>"
                    + (f" · Analyst: {analyst}" if analyst else ""), small), Spacer(1, 10),
          Paragraph("1. Executive summary", h2)]
    summ = [["Flows analysed", f"{n:,}"], ["Malicious flows", f"{len(att):,} ({len(att) / max(n, 1):.1%})"],
            ["Zero-day / unknown", f"{(result['Verdict'] == 'Unknown attack').sum():,}"],
            ["Highest severity", worst_name]]
    if model_info:
        summ.append(["Detection model", f"{model_info.get('model_name')} (trained {model_info.get('trained_at')})"])
    t = Table(summ, colWidths=[5 * cm, 11 * cm]); t.setStyle(TableStyle(grid[:1] + [("FONTSIZE", (0, 0), (-1, -1), 9)]))
    el += [t, Spacer(1, 8)]

    el.append(Paragraph("2. Detections by category", h2))
    vc = result["Verdict"].value_counts()
    rows = [["Category", "Flows", "Share", "Severity"]] + [[k, f"{v:,}", f"{v / n:.1%}", SEVERITY.get(k, "High")] for k, v in vc.items()]
    t = Table(rows, colWidths=[5 * cm, 3 * cm, 3 * cm, 3 * cm]); t.setStyle(TableStyle(grid)); el += [t, Spacer(1, 8)]

    if "Src IP" in result.columns and len(att):
        el.append(Paragraph("3. Top offending sources", h2))
        top = att.groupby("Src IP").agg(Flows=("Verdict", "size"), Main=("Verdict", lambda s: s.mode().iloc[0])).sort_values("Flows", ascending=False).head(10)
        rows = [["Source IP", "Malicious flows", "Main attack type"]] + [[ip, f"{r.Flows:,}", r.Main] for ip, r in top.iterrows()]
        t = Table(rows, colWidths=[5 * cm, 4 * cm, 6 * cm]); t.setStyle(TableStyle(grid)); el += [t, Spacer(1, 8)]

    el.append(Paragraph("4. Most critical flows", h2))
    if len(att):
        a = att.assign(_s=att["Severity"].map(_SEV_ORDER)).sort_values(["_s", "Confidence"], ascending=[True, False]).head(20)
        cols = [c for c in ["Src IP", "Src Port", "Dst IP", "Dst Port"] if c in a.columns] + ["Verdict", "Severity", "Confidence"]
        rows = [cols] + [[(f"{r[c]:.0%}" if c == "Confidence" else str(r[c])) for c in cols] for _, r in a.iterrows()]
        t = Table(rows, repeatRows=1); t.setStyle(TableStyle(grid)); el.append(t)
    else:
        el.append(Paragraph("No malicious flows detected.", body))
    el.append(Spacer(1, 8))

    el.append(Paragraph("5. Recommended response", h2))
    for k in [v for v in vc.index if v != "Benign"]:
        el.append(Paragraph(f"<b>{k}</b> ({SEVERITY.get(k, 'High')}): {MITIGATION.get(k, '')}", body))
    if notes:
        el += [Paragraph("6. Analyst notes", h2), Paragraph(notes.replace("\n", "<br/>"), body)]
    el += [Spacer(1, 14), Paragraph("Generated by ExplainIDS: hybrid CNN-XGBoost + autoencoder open-set detection with SHAP "
                                    "explanations.", small)]
    doc.build(el)
    return buf.getvalue()
